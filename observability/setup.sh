#!/bin/sh
# Self-hosted Langfuse for the agent's traces (lesson 14/24).
#   ./setup.sh          first run: writes .env with random secrets, then starts Langfuse (web, worker and their
#                       stores: Postgres, ClickHouse, Redis, MinIO). Later runs just start it again.
#   ./setup.sh stop     stops the containers (data stays in Docker volumes)
#   ./setup.sh down     removes the containers; add -v by hand to `docker compose down -v` to wipe the data
# UI: http://localhost:3000, user and password in .env (LANGFUSE_INIT_USER_EMAIL / _PASSWORD).
set -eu
cd "$(dirname "$0")"
case "${1:-up}" in
  stop) docker compose stop; exit 0 ;;
  down) docker compose down; exit 0 ;;
esac
if [ ! -f .env ]; then
  hex() { openssl rand -hex "$1"; }
  cat > .env <<ENV
# Generated by setup.sh on $(date -u +%Y-%m-%d). Local secrets: git-ignored, never commit.
TELEMETRY_ENABLED=false
NEXTAUTH_SECRET=$(hex 32)
SALT=$(hex 32)
ENCRYPTION_KEY=$(hex 32)
POSTGRES_PASSWORD=$(hex 16)
DATABASE_URL=postgresql://postgres:\${POSTGRES_PASSWORD}@postgres:5432/postgres
CLICKHOUSE_PASSWORD=$(hex 16)
REDIS_AUTH=$(hex 16)
MINIO_ROOT_PASSWORD=$(hex 16)
LANGFUSE_S3_EVENT_UPLOAD_SECRET_ACCESS_KEY=\${MINIO_ROOT_PASSWORD}
LANGFUSE_S3_MEDIA_UPLOAD_SECRET_ACCESS_KEY=\${MINIO_ROOT_PASSWORD}
LANGFUSE_S3_BATCH_EXPORT_SECRET_ACCESS_KEY=\${MINIO_ROOT_PASSWORD}
# Headless initialisation: the org, project, API keys and login exist from the first start, no sign-up screen.
LANGFUSE_INIT_ORG_ID=tiny-agent
LANGFUSE_INIT_ORG_NAME="Tiny Agent"
LANGFUSE_INIT_PROJECT_ID=tiny-coding-agent
LANGFUSE_INIT_PROJECT_NAME="Tiny Coding Agent"
LANGFUSE_INIT_PROJECT_PUBLIC_KEY=pk-lf-$(hex 16)
LANGFUSE_INIT_PROJECT_SECRET_KEY=sk-lf-$(hex 16)
LANGFUSE_INIT_USER_EMAIL=owner@langfuse.local
LANGFUSE_INIT_USER_NAME=Owner
LANGFUSE_INIT_USER_PASSWORD=$(hex 12)
# Read by telemetry.py (the agent side): the same three values work for Langfuse Cloud.
LANGFUSE_HOST=http://localhost:3000
ENV
  echo "wrote .env with new secrets"
fi
# Only what the agent needs: web + worker pull in their four stores; the AI gateway service is left out.
docker compose up -d langfuse-web langfuse-worker
echo "waiting for http://localhost:3000 ..."
i=0
until curl -fs http://localhost:3000/api/public/health >/dev/null 2>&1; do
  i=$((i + 1)); [ "$i" -gt 90 ] && { echo "not healthy after 3 min: docker compose logs langfuse-web"; exit 1; }
  sleep 2
done
echo "Langfuse is up: http://localhost:3000 (login: see LANGFUSE_INIT_USER_EMAIL / _PASSWORD in $(pwd)/.env)"
